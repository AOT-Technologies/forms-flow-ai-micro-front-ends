// jsdom does not implement window.matchMedia; react-bootstrap components
// (via @restart/hooks useMediaQuery) require it, so provide a static shim.
Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
});
