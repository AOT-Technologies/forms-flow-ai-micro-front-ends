// jsdom does not implement window.matchMedia; react-bootstrap's Offcanvas
// (via @restart/hooks useMediaQuery) requires it, so provide a static shim.
Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
});
